/* ═══ CYPH partner deck — build ═══
   Writes partners.html: the non-VC deck served at partners.cyph.city.

   Nothing in it is authored twice. Six of its eight slides are lifted out of
   index.html verbatim, by id, and keep that id — so every `#sN` rule in
   styles.css applies to them unchanged. The other two are partials in
   partners/: hiw.html (how it works: the s5 stack with the s6/s8/s9 content
   laid out beside it) and close.html (s15 with the partner copy). hiw.html
   pulls its transit map and press/logo column out of index.html too, through
   `<!-- @include index.html <selector> -->` lines.

   The shell (head, router, HUD, gate, loaders) is index.html's own, edited in
   place: every edit below is an exact-match replace that throws if its anchor
   has moved, so a change to index.html fails the build loudly instead of
   producing a half-partner deck.

   Run:  npm run partners   (build + export the partner PDF and phone pages)
         node tools/build-partners.mjs   (build only) */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => fs.readFileSync(path.join(ROOT, p), "utf8");

/* the partner running order: investor slide ids, or a partial in partners/ */
const ORDER = ["s0", "s1", "s2", "s3", "s4", "partners/hiw.html", "s13", "partners/close.html"];

const src = read("index.html");

/* ── pull one element out of index.html, start tag through matching close ── */
function extract(html, startIdx, label) {
  const tag = html.slice(startIdx + 1).match(/^[a-z0-9]+/i)[0];
  const re = new RegExp(`<(/?)${tag}\\b[^>]*?(/?)>`, "gi");
  re.lastIndex = startIdx;
  let depth = 0;
  for (let m; (m = re.exec(html)); ) {
    if (m[2] === "/") continue; // self-closing
    depth += m[1] ? -1 : 1;
    if (depth === 0) return html.slice(startIdx, re.lastIndex);
  }
  throw new Error(`unbalanced <${tag}> for ${label}`);
}

/* the start of the tag carrying an attribute; the tag may span lines */
function findTag(html, attrRe, label) {
  const m = html.match(attrRe);
  if (!m) throw new Error(`index.html: ${label} not found`);
  const start = html.lastIndexOf("<", m.index);
  return start;
}

function byId(id) {
  return extract(src, findTag(src, new RegExp(`\\sid="${id}"`), `#${id}`), `#${id}`);
}
function byClass(cls) {
  return extract(src, findTag(src, new RegExp(`\\sclass="${cls}"`), `.${cls}`), `.${cls}`);
}
function include(partial) {
  return partial.replace(/<!-- @include index\.html ([#.])([\w-]+) -->/g, (_, kind, name) =>
    kind === "#" ? byId(name) : byClass(name),
  );
}

const slides = ORDER.map((s) => (s.includes("/") ? include(read(s)) : "      " + byId(s))).join(
  "\n\n",
);

/* ── the shell ── */
let out = src;
function swap(from, to, label) {
  if (!out.includes(from)) throw new Error(`index.html: anchor for ${label} moved`);
  out = out.replace(from, to);
}

/* everything between the HUD's xp bar and the xp burst is slides */
const slidesStart = out.indexOf("<!-- LEVEL 0: TITLE -->");
const slidesEnd = out.indexOf('<div class="xp-burst"');
if (slidesStart < 0 || slidesEnd < 0) throw new Error("index.html: slide region anchors moved");
out = out.slice(0, slidesStart) + slides.trimStart() + "\n\n      " + out.slice(slidesEnd);

swap(
  "<!doctype html>\n<html lang=\"en\">",
  "<!doctype html>\n<!-- generated by tools/build-partners.mjs from index.html + partners/ — never edit by hand -->\n<html lang=\"en\" data-pages=\"assets/partner-pages/\">",
  "html tag",
);
swap("<title>cyph - pitch deck</title>", "<title>cyph - partner deck</title>", "title");
swap(
  '<meta property="og:url" content="https://cypher-nyc.github.io/cyph-deck/" />',
  '<meta property="og:url" content="https://partners.cyph.city/" />',
  "og:url",
);
/* partners.css rides on styles.css, desktop path only */
swap(
  'l.href = phone ? "mobile.css" : "styles.css";\n        document.head.appendChild(l);',
  'l.href = phone ? "mobile.css" : "styles.css";\n        document.head.appendChild(l);\n        if (!phone) {\n          var p = document.createElement("link");\n          p.rel = "stylesheet";\n          p.href = "partners/partners.css";\n          document.head.appendChild(p);\n        }',
  "router stylesheet",
);

/* chapter nav: cyph / founders / problem / solution / close */
const navStart = out.indexOf('<nav class="hud-nav">');
const navEnd = out.indexOf("</nav>", navStart) + "</nav>".length;
if (navStart < 0) throw new Error("index.html: hud-nav moved");
const nav = [
  ["cyph", 0],
  ["founders", 1],
  ["problem", 2],
  ["solution", 4],
  ["close", 7],
]
  .map(([label, i]) => `          <button class="hud-nav-btn" onclick="goTo(${i})">${label}</button>`)
  .join('\n          <span class="hud-nav-sep">/</span>\n');
out =
  out.slice(0, navStart) +
  `<nav class="hud-nav">\n${nav.replace('class="hud-nav-btn"', 'class="hud-nav-btn active"')}\n        </nav>` +
  out.slice(navEnd);

swap('<div class="hud-counter" id="hudCtr">01/16</div>', '<div class="hud-counter" id="hudCtr">01/08</div>', "hud counter");
swap('<div class="bhud-counter" id="bhudCtr">01/16</div>', '<div class="bhud-counter" id="bhudCtr">01/08</div>', "bhud counter");

/* no revenue bar on the partner deck */
const revLabel = out.indexOf('<div class="hud-bar-label">revenue</div>');
if (revLabel < 0) throw new Error("index.html: revenue bar moved");
const revStart = out.lastIndexOf('<div class="hud-bar">', revLabel);
out = out.slice(0, revStart) + out.slice(revStart + extract(out, revStart, "revenue bar").length).replace(/^\s*\n/, "");

/* the gate logs this surface as `partners`; no version list here */
swap(
  '<script src="auth.js" data-versions="/deck/versions.json"></script>',
  '<script src="auth.js" data-viewed="partners"></script>',
  "auth.js tag",
);
swap('s.src = phone ? "mobile.js" : "deck.js";', 's.src = phone ? "mobile.js" : "partners/partners.js";', "deck loader");

fs.writeFileSync(path.join(ROOT, "partners.html"), out);
console.log(`wrote partners.html — ${ORDER.length} slides`);
